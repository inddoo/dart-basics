void main() {
  // Operator Aritmatika
  int a = 10;
  int b = 3;
  
  print('Penjumlahan: ${a + b}'); // 13
  print('Pengurangan: ${a - b}'); // 7
  print('Perkalian: ${a * b}'); // 30
  print('Pembagian: ${a / b}'); // 3.333...
  print('Pembagian Integer: ${a ~/ b}'); // 3
  print('Modulus: ${a % b}'); // 1
  
  // Increment & Decrement
  int c = 6;
  c = c + 6; // c = 12
  print('Hasil: $c');
}